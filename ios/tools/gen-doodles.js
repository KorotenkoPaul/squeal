// Writes ios/Squeal/UI/Chat/DoodleData.swift from the DOODLE library in web/template.html, so the app draws the chat
// wallpaper from the very same drawings. Usage: node ios/tools/gen-doodles.js   (run again when DOODLE changes)
// One doodle = its elements joined by ";", each "KIND|field|field…":
//   P|path data|matrix|dash     C|cx|cy|r     R|x|y|w|h|rx|matrix     T|text|x|y|font size
// matrix: "a b c d e f" of the element's transform (empty: none); dash: "2 2.4" (empty: none).
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '../..');
const html = fs.readFileSync(path.join(root, 'web/template.html'), 'utf8');
const src = /const DOODLE = (\{[\s\S]*?\n\});/.exec(html);
if (!src) throw new Error('DOODLE not found in web/template.html');
const DOODLE = eval('(' + src[1] + ')');

const mul = (m, n) => [m[0] * n[0] + m[2] * n[1], m[1] * n[0] + m[3] * n[1], m[0] * n[2] + m[2] * n[3], m[1] * n[2] + m[3] * n[3],
  m[0] * n[4] + m[2] * n[5] + m[4], m[1] * n[4] + m[3] * n[5] + m[5]];
function matrix(t) {
  if (!t) return '';
  let m = [1, 0, 0, 1, 0, 0];
  const re = /(\w+)\(([^)]*)\)/g; let x;
  while ((x = re.exec(t))) {
    const a = x[2].trim().split(/[\s,]+/).map(Number);
    if (x[1] === 'translate') m = mul(m, [1, 0, 0, 1, a[0], a[1] || 0]);
    else if (x[1] === 'scale') m = mul(m, [a[0], 0, 0, a.length > 1 ? a[1] : a[0], 0, 0]);
    else if (x[1] === 'rotate') { const r = a[0] * Math.PI / 180, c = Math.cos(r), s = Math.sin(r), cx = a[1] || 0, cy = a[2] || 0;
      m = mul(mul(mul(m, [1, 0, 0, 1, cx, cy]), [c, s, -s, c, 0, 0]), [1, 0, 0, 1, -cx, -cy]); }
    else throw new Error('transform not handled: ' + x[1]);
  }
  return m.map(v => +v.toFixed(6)).join(' ');
}
const out = {};
for (const [name, svg] of Object.entries(DOODLE)) {
  const els = []; const re = /<(\w+)([^>]*?)(?:\/>|>([^<]*)<\/\1>)/g; let x;
  while ((x = re.exec(svg))) {
    const a = {}; x[2].replace(/([\w-]+)="([^"]*)"/g, (_, k, v) => { a[k] = v; });
    const known = k => { for (const key of Object.keys(a)) if (!k.includes(key)) throw new Error(`${name}: <${x[1]}> attribute not handled: ${key}`); };
    if (x[1] === 'path') { known(['d', 'transform', 'stroke-dasharray']); els.push(['P', a.d, matrix(a.transform), a['stroke-dasharray'] || ''].join('|')); }
    else if (x[1] === 'circle') { known(['cx', 'cy', 'r']); els.push(['C', a.cx, a.cy, a.r].join('|')); }
    else if (x[1] === 'rect') { known(['x', 'y', 'width', 'height', 'rx', 'transform']); els.push(['R', a.x, a.y, a.width, a.height, a.rx || 0, matrix(a.transform)].join('|')); }
    else if (x[1] === 'text') { known(['x', 'y', 'text-anchor', 'font-size', 'font-family', 'stroke', 'fill', 'fill-opacity']); els.push(['T', x[3], a.x, a.y, a['font-size']].join('|')); }
    else throw new Error(`${name}: element not handled: ${x[1]}`);
  }
  if (!els.length || els.some(e => /[;"\\]/.test(e))) throw new Error(name + ': cannot be written');
  out[name] = els.join(';');
}
const swift = `// GENERATED by ios/tools/gen-doodles.js from the DOODLE library in web/template.html. Do not edit by hand.
enum DoodleData {
    static let all: [String: String] = [
${Object.entries(out).map(([k, v]) => `        "${k}": "${v}",`).join('\n')}
    ]
}
`;
fs.mkdirSync(path.join(root, 'ios/Squeal/UI/Chat'), { recursive: true });
fs.writeFileSync(path.join(root, 'ios/Squeal/UI/Chat/DoodleData.swift'), swift);
console.log(Object.keys(out).length + ' doodles');
